// ─── Pitch Detector ───────────────────────────────────────────────────────────
function PitchDetector({referenceNotes}) {
  const [listening,setListening]=useState(false);
  const [pitch,setPitch]=useState(null);
  const [noteName,setNoteName]=useState(null);
  const [score,setScore]=useState(null);
  const [history,setHistory]=useState([]);
  const [error,setError]=useState(null);
  const ctxRef=useRef(null),streamRef=useRef(null),rafRef=useRef(null);
  const stopListen=useCallback(()=>{
    cancelAnimationFrame(rafRef.current);
    if(streamRef.current)streamRef.current.getTracks().forEach(t=>t.stop());
    if(ctxRef.current)ctxRef.current.close();
    ctxRef.current=null;streamRef.current=null;setListening(false);
  },[]);
  const startListen=useCallback(async()=>{
    setError(null);
    try{
      const stream=await navigator.mediaDevices.getUserMedia({audio:true});
      streamRef.current=stream;
      const ctx=new(window.AudioContext||window.webkitAudioContext)();
      ctxRef.current=ctx;
      const analyser=ctx.createAnalyser();analyser.fftSize=2048;
      ctx.createMediaStreamSource(stream).connect(analyser);
      setListening(true);
      const buf=new Float32Array(analyser.fftSize);
      const loop=()=>{
        analyser.getFloatTimeDomainData(buf);
        const f=detectPitch(buf,ctx.sampleRate);
        if(f&&f>60&&f<1400){
          const n=freqToNote(f),s=scorePitch(f,referenceNotes);
          setPitch(Math.round(f));setNoteName(n);setScore(s);
          setHistory(prev=>[...prev.slice(-11),{f:Math.round(f),n,s}]);
        }
        rafRef.current=requestAnimationFrame(loop);
      };
      loop();
    }catch{setError("Microphone access denied.");setListening(false);}
  },[referenceNotes]);
  useEffect(()=>()=>stopListen(),[stopListen]);
  const avg=history.length>0?Math.round(history.filter(h=>h.s).reduce((a,h)=>a+h.s.score,0)/Math.max(1,history.filter(h=>h.s).length)):null;
  return (
    <div style={{background:P.surface,border:`1px solid ${P.border}`,borderRadius:12,padding:18}}>
      <div style={{color:P.muted,fontSize:11,fontWeight:700,letterSpacing:"0.1em",marginBottom:12}}>PITCH DETECTOR</div>
      {error&&<div style={{color:P.red,fontSize:12,marginBottom:10,padding:"8px 12px",background:P.red+"22",borderRadius:8}}>{error}</div>}
      {listening&&(
        <div style={{marginBottom:12}}>
          <div style={{display:"flex",gap:8,marginBottom:10}}>
            {[["NOTE",noteName||"—",P.teal],["HZ",pitch?`${pitch}`:"…",P.teal],score?["ACC",`${score.score}%`,score.color]:null,avg?["AVG",`${avg}%`,P.accent]:null].filter(Boolean).map(([l,v,c])=>(
              <div key={l} style={{flex:1,background:P.card,borderRadius:8,padding:"8px 6px",textAlign:"center"}}>
                <div style={{color:P.muted,fontSize:9,letterSpacing:"0.1em"}}>{l}</div>
                <div style={{color:c,fontSize:16,fontWeight:800}}>{v}</div>
              </div>
            ))}
          </div>
          <div style={{display:"flex",gap:3,height:28,alignItems:"flex-end"}}>
            {Array.from({length:12}).map((_,i)=>{
              const h=history[history.length-12+i];
              return <div key={i} style={{flex:1,borderRadius:2,background:h?.s?h.s.color+"99":P.border,height:h?.s?`${h.s.score}%`:"8%",transition:"height 0.1s"}}/>;
            })}
          </div>
        </div>
      )}
      <button onClick={listening?stopListen:startListen} style={{width:"100%",padding:"9px 0",borderRadius:8,fontWeight:800,fontSize:13,border:"none",cursor:"pointer",background:listening?P.red+"cc":P.accent,color:"#0a0a0f",transition:"background 0.2s"}}>
        {listening?"■ STOP":"⏺ PITCH DETECTION"}
      </button>
      {!listening&&avg&&<div style={{marginTop:9,padding:"7px 12px",background:P.card,borderRadius:8,border:`1px solid ${P.border}`}}><span style={{color:avg>75?P.teal:avg>50?P.accent:P.red,fontWeight:700,fontSize:13}}>{avg}%</span><span style={{color:P.textSoft,fontSize:12}}>{avg>75?" — Excellent!":avg>50?" — Keep going.":" — Slow it down."}</span></div>}
    </div>
  );
}

