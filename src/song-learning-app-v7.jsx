function midiToFreq(m) { return 440*Math.pow(2,(m-69)/12); }
function getCtx() { return new (window.AudioContext||window.webkitAudioContext)(); }

// Schedule a click at a precise audio time — runs on the audio thread, not JS thread
function scheduleClick(ctx, time, accent) {
  const o = ctx.createOscillator(), g = ctx.createGain();
  o.connect(g); g.connect(ctx.destination);
  o.frequency.value = accent ? 1200 : 800; o.type = "square";
  g.gain.setValueAtTime(accent ? 0.28 : 0.14, time);
  g.gain.exponentialRampToValueAtTime(0.0001, time + 0.04);
  o.start(time); o.stop(time + 0.05);
}

function playChord(ctx, notes, dur = 1.8) {
  notes.forEach((midi, i) => {
    const o = ctx.createOscillator(), g = ctx.createGain();
    o.connect(g); g.connect(ctx.destination);
    o.type = "triangle"; o.frequency.value = midiToFreq(midi);
    g.gain.setValueAtTime(0, ctx.currentTime);
    g.gain.linearRampToValueAtTime(0.14/notes.length, ctx.currentTime+0.01+i*0.03);
    g.gain.exponentialRampToValueAtTime(0.0001, ctx.currentTime+dur);
    o.start(ctx.currentTime+i*0.03); o.stop(ctx.currentTime+dur+0.1);
  });
}

// Lookahead metronome hook — audio-clock-locked, no JS event loop drift
function useMetronome(songBpm, timeSig) {
  const [running,  setRunning]  = useState(false);
  const [beat,     setBeat]     = useState(0);
  const [tempo,    setTempo]    = useState(songBpm);
  const [mult,     setMult]     = useState(1);
  const ctxRef    = useRef(null);
  const timerRef  = useRef(null);
  const nextRef   = useRef(0);   // next scheduled audio time
  const beatRef   = useRef(0);   // current beat count
  const bpb = parseInt(timeSig.split("/")[0]);

  // Keep refs in sync with state so scheduler closure always has latest values
  const tempoRef = useRef(tempo);
  const multRef  = useRef(mult);
  useEffect(() => { tempoRef.current = tempo; }, [tempo]);
  useEffect(() => { multRef.current = mult;   }, [mult]);

  const scheduler = useCallback(() => {
    const ctx = ctxRef.current;
    if (!ctx) return;
    // Look 120ms ahead — schedule any beats due within that window
    const lookAhead = 0.12;
    const interval  = 60 / (tempoRef.current * multRef.current);
    while (nextRef.current < ctx.currentTime + lookAhead) {
      const b = beatRef.current % bpb;
      scheduleClick(ctx, nextRef.current, b === 0);
      // Update visual beat counter at the right time via setTimeout
      const delay = Math.max(0, (nextRef.current - ctx.currentTime) * 1000);
      const capturedB = b;
      setTimeout(() => setBeat(capturedB), delay);
      nextRef.current += interval;
      beatRef.current++;
    }
    timerRef.current = setTimeout(scheduler, 25); // re-run every 25ms
  }, [bpb]);

  const stop = useCallback(() => {
    clearTimeout(timerRef.current);
    setRunning(false); setBeat(0);
    beatRef.current = 0; nextRef.current = 0;
  }, []);

  const start = useCallback(() => {
    if (!ctxRef.current) ctxRef.current = getCtx();
    const ctx = ctxRef.current;
    if (ctx.state === "suspended") ctx.resume();
    beatRef.current = 0;
    nextRef.current = ctx.currentTime + 0.05; // small buffer before first beat
    setRunning(true);
    scheduler();
  }, [scheduler]);

  // Restart cleanly when tempo or mult changes while running
  useEffect(() => {
    if (running) { stop(); setTimeout(start, 30); }
  }, [tempo, mult]); // eslint-disable-line

  useEffect(() => () => clearTimeout(timerRef.current), []);

  return { running, beat, tempo, setTempo, mult, setMult, start, stop, bpb };
}

// Pitch detection (autocorrelation)
function detectPitch(buf, sr) {
  const SIZE = buf.length, MAX = Math.floor(SIZE/2);
  let best=-1, bestC=0, rms=0;
  for (let i=0;i<SIZE;i++) rms+=buf[i]*buf[i];
  if (Math.sqrt(rms/SIZE)<0.01) return null;
  let last=1, found=false;
  for (let off=8;off<MAX;off++) {
    let c=0; for (let i=0;i<MAX;i++) c+=Math.abs(buf[i]-buf[i+off]);
    c=1-c/MAX;
    if (c>0.9&&c>last){found=true;if(c>bestC){bestC=c;best=off;}}
    else if(found)break; last=c;
  }
  return best===-1?null:sr/best;
}
function freqToNote(f) {
  if(!f||f<60)return null;
  const N=["C","C#","D","D#","E","F","F#","G","G#","A","A#","B"];
  const m=Math.round(12*Math.log2(f/440)+69);
  return N[m%12]+Math.floor(m/12-1);
}
function scorePitch(det,ref) {
  if(!det||!ref?.length)return null;
  const dm=Math.round(12*Math.log2(det/440)+69);
  const min=Math.min(...ref.map(r=>Math.abs(dm-Math.round(12*Math.log2(r/440)+69))));
  if(min===0)return{score:100,label:"Perfect",   color:P.teal};
  if(min===1)return{score:85, label:"Very Close",color:P.green};
  if(min===2)return{score:65, label:"Close",     color:P.accent};
  if(min<=4) return{score:40, label:"Off Pitch", color:P.gold};
  return{score:15,label:"Way Off",color:P.red};
}

